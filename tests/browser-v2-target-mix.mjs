import assert from 'node:assert/strict';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
const browser=await chromium.launch({headless:true,executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE||'/usr/bin/chromium'});
try {
 const page=await browser.newPage();
 await page.goto('http://127.0.0.1:4173/jazz-ear-lab-v2/');
 await page.locator('[data-preset-id="recognition-guides"]').getByRole('button',{name:'Customize',exact:true}).click();
 await page.getByRole('button',{name:'Targets',exact:true}).click();
 await page.getByLabel('Voice 1 volume',{exact:true}).fill('150');
 await page.getByLabel('Voice 1 volume',{exact:true}).dispatchEvent('change');
 await page.getByRole('button',{name:'Audition C7',exact:true}).click();
 const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('jazzEarLab:v2:presets')));
 assert.equal(saved.find(p=>p.id==='recognition-guides').config.voiceLevels[0],1.5);
 assert.deepEqual(saved.find(p=>p.id==='recognition-guides').config.targetPools['7'],['3','b7']);
 assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('jazzEarLab:v2:sessions')||'[]').length),0);
 await page.screenshot({path:'/tmp/v2-targets-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.screenshot({path:'/tmp/v2-targets-mobile.png',fullPage:true});
 await page.getByRole('button',{name:'Start practice',exact:true}).click();
 await page.waitForURL(/#practice$/);
 await page.waitForFunction(()=>document.querySelectorAll('.answers button:not(:disabled)').length===12);
 await page.locator('.answers button:not(:disabled)').first().click();
 await page.getByRole('button',{name:'Stop',exact:true}).click();
 await page.waitForURL(/#results/);
 await page.goto('http://127.0.0.1:4173/jazz-ear-lab-v2/#insights');
 await page.getByRole('button',{name:'Overall',exact:true}).waitFor();
 await page.getByRole('heading',{name:'Combined degree accuracy',exact:true}).waitFor();
 assert.equal(await page.getByLabel('Comparable practice conditions').count(),0);
 await page.screenshot({path:'/tmp/v2-insights-mobile.png',fullPage:true});
 await page.setViewportSize({width:1440,height:1000});await page.screenshot({path:'/tmp/v2-insights-desktop.png',fullPage:true});
 await page.getByRole('button',{name:'Customize focus',exact:true}).first().click();
 await page.getByRole('button',{name:'Targets',exact:true}).click();
 const group=page.getByRole('group',{name:'7',exact:true});
 await group.getByLabel('9',{exact:true}).check();
 const focus=await page.evaluate(()=>JSON.parse(localStorage.getItem('jazzEarLab:v2:presets')).find(p=>p.name.startsWith('Focus:')));
 assert.ok(focus.config.targetPools['7'].includes('9'));
 assert.equal(focus.config.voiceLevels[0],1.5);
 console.log('Passed: Customize mix/pools, unrecorded audition, frozen practice, Results and Overall Insights; mobile overflow.');
}finally{await browser.close();}
